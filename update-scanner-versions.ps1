    description = "Pinned versions of every scanner integrated into the AI Code Scanner. Auto-generated by update-scanner-versions.ps1."
    generated_at = (Get-Date -Format "yyyy-MM-ddTHH:mm:ssZ")
    scanners = $scanners
    host_runtime = @{
        python = ">=3.11"
        node = ">=20"
        go = ">=1.22"
        jdk = ">=17"
        docker_engine = ">=24.0"
        container_base_image = "python:3.11-slim-bookworm"
    }
}

