# AI Code Scanner - regenerate scanner_versions.json from installed binaries.
# Runs version command on each tool, parses the output, writes a canonical
# manifest at the repo root.

$ErrorActionPreference = "Continue"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $root

# Make Trivy reachable if PATH has not been picked up yet
if (-not (Get-Command trivy -ErrorAction SilentlyContinue)) {
    $env:Path += ";C:\Tools\trivy"
}

function Capture-Version {
    param([string]$Command, [string]$VersionFlag, [string]$Regex)
    try {
        $raw = & $Command $VersionFlag 2>&1 | Out-String
        if ($raw -match $Regex) {
            return $matches[1]
        }
    } catch {}
    return $null
}

